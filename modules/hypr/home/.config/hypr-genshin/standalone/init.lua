-- Genshin standalone core: loader and helpers
local HOME = os.getenv("HOME") or ""
local root = assert(debug.getinfo(1, "S").source:match("^@(.*)/"), "not loaded from a file")

local S = { home = HOME, root = root, errors = 0 }
_G.genshin = S

S.logfile = (os.getenv("XDG_CACHE_HOME") or (HOME .. "/.cache")) .. "/genshin-standalone.log"
do
    local f = io.open(S.logfile, "w")
    if f then
        f:write(os.date("%F %T"), " load\n")
        f:close()
    end
end

function S.log(msg)
    local f = io.open(S.logfile, "a")
    if f then
        f:write(tostring(msg), "\n")
        f:close()
    end
end

function S.fail(where, err)
    S.errors = S.errors + 1
    S.log("ERROR " .. where .. ": " .. tostring(err))
end

function S.exists(path)
    local f = io.open(path, "r")
    if f then
        f:close()
        return true
    end
    return false
end

-- hl.config wrapper: a bad key only loses that one table
function S.config(tbl, name)
    local ok, err = pcall(hl.config, tbl)
    if not ok then
        S.fail("config " .. (name or "?"), err)
    end
end

-- bind wrapper: mk is a thunk that builds the dispatcher, so a missing
-- hl.dsp.* function is caught too
function S.bind(keys, mk, opts)
    local ok, err = pcall(function()
        hl.bind(keys, mk(), opts)
    end)
    if not ok then
        S.fail("bind " .. keys, err)
    end
end

function S.exec(cmd)
    return function()
        return hl.dsp.exec_cmd(cmd)
    end
end

function S.fn(f)
    return function()
        return f
    end
end

for _, name in ipairs({ "env", "base", "rules", "binds", "startup" }) do
    local ok, err = pcall(dofile, root .. "/" .. name .. ".lua")
    if not ok then
        S.fail(name .. ".lua", err)
    end
end

-- Monitor config generated by nwg-displays (same file HyDE loaded)
local monitors = HOME .. "/.config/hypr/monitors.lua"
if S.exists(monitors) then
    local ok, err = pcall(dofile, monitors)
    if not ok then
        S.fail("monitors.lua", err)
    end
end

-- Genshin theme layer (borders, animations, cursor, alt-tab) always loads last
local theme = HOME .. "/.config/hypr-genshin/genshin.lua"
if S.exists(theme) then
    local ok, err = pcall(dofile, theme)
    if not ok then
        S.fail("genshin.lua", err)
    end
end

-- Regenerate the SUPER + / keybind hint on every load (same as HyDE)
pcall(hl.exec_cmd, "command -v hyde-shell >/dev/null 2>&1 && hyde-shell keybinds_hint --reload || true")

if S.errors > 0 then
    S.log("TOTAL ERRORS: " .. S.errors)
    pcall(hl.exec_cmd, "notify-send -a Paimon 'Genshin standalone' '" .. S.errors .. " error(s), see " .. S.logfile .. "'")
else
    S.log("OK: no errors")
end
