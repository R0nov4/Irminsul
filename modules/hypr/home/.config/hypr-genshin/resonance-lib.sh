#!/usr/bin/env bash
# Genshin Resonance library — sourced by theme-select.sh and wallpaper-hooks.d/10-resonance.sh
CFG="$HOME/.config/hypr-genshin"
RES_CACHE="$HOME/.cache/genshin-theme"
RES_STATE="$CFG/element-override.conf"
RES_WAYBAR="$HOME/.config/waybar-genshin"
RES_WSTATE="$HOME/.cache/hypr-genshin"          # wallpaper.sh state dir
mkdir -p "$RES_CACHE/thumbs"

_im() { command -v magick || command -v convert; }

res_key() {
    printf '%s-%s' "$(printf '%s' "$1" | md5sum | cut -c1-12)" "$(stat -c %Y "$1" 2>/dev/null || echo 0)"
}

# Wallpaper library dir (honours WALL_DIR in wallpaper.conf)
res_wall_dir() {
    (
        CFG_DIR="$CFG"
        WALL_DIR="$CFG/wallpapers"
        [ -f "$CFG/wallpaper.conf" ] && . "$CFG/wallpaper.conf" 2>/dev/null
        printf '%s' "$WALL_DIR"
    )
}

# Active theme = active "region" of wallpaper.sh
res_active_theme() {
    local a
    a=$(cat "$RES_WSTATE/collection" 2>/dev/null || true)
    printf '%s' "${a:-all}"
}

# palette_of IMG → up to 3 lines: "BASE HI LO Name"  (hex without #)
palette_of() {
    local im pf
    im=$(_im) || return 1
    pf="$RES_CACHE/$(res_key "$1").pal3"
    if [ ! -s "$pf" ]; then
        "$im" "$1[0]" -resize 64x64! -depth 8 txt:- 2>/dev/null \
          | sed -nE 's/.*srgba?\(([0-9]+),([0-9]+),([0-9]+).*/\1 \2 \3/p' \
          | awk '
            function hue(r,g,b,   mx,mn,d,h) {
                mx=r; if (g>mx) mx=g; if (b>mx) mx=b
                mn=r; if (g<mn) mn=g; if (b<mn) mn=b
                d=mx-mn; if (d==0) return 0
                if (mx==r) h=(g-b)/d; else if (mx==g) h=2+(b-r)/d; else h=4+(r-g)/d
                h*=60; if (h<0) h+=360
                return h
            }
            function hname(h) {
                if (h<15 || h>=345) return "Crimson"
                if (h<40) return "Amber"
                if (h<65) return "Gold"
                if (h<150) return "Emerald"
                if (h<190) return "Teal"
                if (h<250) return "Azure"
                if (h<290) return "Violet"
                return "Rose"
            }
            {
                r=$1; g=$2; b=$3
                mx=r; if (g>mx) mx=g; if (b>mx) mx=b
                mn=r; if (g<mn) mn=g; if (b<mn) mn=b
                v=mx/255; s=(mx-mn)/(mx+1)
                if (v<0.35 || v>0.97 || s<0.22) next
                k = int(r/48) "," int(g/48) "," int(b/48)
                w[k]+=s*v; sr[k]+=r; sg[k]+=g; sb[k]+=b; cn[k]++
            }
            END {
                cnt=0
                for (i=0; i<3; i++) {
                    best=""; bw=0
                    for (k in w) {
                        if (k in used) continue
                        r=sr[k]/cn[k]; g=sg[k]/cn[k]; b=sb[k]/cn[k]
                        h=hue(r,g,b); ok=1
                        for (j=0; j<cnt; j++) {
                            dh=h-ch[j]; if (dh<0) dh=-dh; if (dh>180) dh=360-dh
                            if (dh<35) ok=0
                        }
                        if (ok && w[k]>bw) { bw=w[k]; best=k }
                    }
                    if (best=="") break
                    used[best]=1
                    r=sr[best]/cn[best]; g=sg[best]/cn[best]; b=sb[best]/cn[best]
                    h=hue(r,g,b); ch[cnt]=h; cnt++
                    mx=r; if (g>mx) mx=g; if (b>mx) mx=b
                    if (mx>0 && mx<200) { f=200/mx; r*=f; g*=f; b*=f }
                    hr=r+(255-r)*0.45; hg=g+(255-g)*0.45; hb=b+(255-b)*0.45
                    printf "%02x%02x%02x %02x%02x%02x %02x%02x%02x %s\n", \
                        int(r),int(g),int(b), int(hr),int(hg),int(hb), int(r*0.55),int(g*0.55),int(b*0.55), hname(h)
                }
                if (cnt==0) print "d3bc8e f4e8c1 8a7550 Gold"
            }' > "$pf"
    fi
    cat "$pf"
}

# res_apply NAME BASE HI LO
res_apply() {
    local name="$1" base="$2" hi="$3" lo="$4"
    [ -n "$base" ] || return 0
    local C1="${hi}ff" C2="${base}ff" C3="${lo}aa"
    local HEX="#$base" HEX_HI="#$hi" HEX_LO="#$lo"

    hyprctl keyword general:col.active_border "rgba($C1) rgba($C2) rgba($C3) rgba($C1) 45deg" >/dev/null 2>&1
    hyprctl keyword group:col.border_active "rgba($C1) rgba($C2) 45deg" >/dev/null 2>&1

    {
        echo "# Auto-generated by Genshin Resonance"
        echo "NAME=\"$name\""
        echo "HEX=\"$HEX\""
        echo "HEX_HI=\"$HEX_HI\""
        echo "HEX_LO=\"$HEX_LO\""
        echo "C1=\"$C1\""
        echo "C2=\"$C2\""
        echo "C3=\"$C3\""
    } > "$RES_STATE"

    # Rofi accent (any .rasi that defines gold: / gold-bright: variables)
    local rasi
    for rasi in "$HOME/.config/rofi-genshin/"*.rasi; do
        [ -f "$rasi" ] || continue
        sed -i -E "s/(gold:[[:space:]]*)#[0-9a-fA-F]{6};/\1${HEX};/" "$rasi"
        sed -i -E "s/(gold-bright:[[:space:]]*)#[0-9a-fA-F]{6};/\1${HEX_HI};/" "$rasi"
    done

    # Waybar accent (add: @import "colors.css"; at top of style.css, then use @accent)
    if [ -d "$RES_WAYBAR" ]; then
        {
            echo "@define-color accent $HEX;"
            echo "@define-color accent_hi $HEX_HI;"
            echo "@define-color accent_lo $HEX_LO;"
        } > "$RES_WAYBAR/colors.css"
        pkill -SIGUSR2 -x waybar 2>/dev/null || true
    fi
}

# Strongest colour of an image
res_from_image() {
    local l b h lo n
    l=$(palette_of "$1" | head -n1)
    [ -n "$l" ] || return 1
    read -r b h lo n <<< "$l"
    res_apply "$n" "$b" "$h" "$lo"
}

# res_theme_apply THEME IMG : fixed accent of the theme if it has one, else colours of IMG
res_theme_apply() {
    local coll="${1:-all}" img="${2:-}" tf
    tf="$(res_wall_dir)/$coll/.theme"
    if [ "$coll" != all ] && [ -f "$tf" ] && grep -q '^ACCENT="fixed"' "$tf"; then
        (
            . "$tf"
            res_apply "${NAME:-Theme}" "${BASE:-}" "${HI:-}" "${LO:-}"
        )
    elif [ -f "$img" ]; then
        res_from_image "$img"
    fi
    return 0
}
